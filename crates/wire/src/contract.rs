#[must_use]
pub fn sent() -> Schema {
    bundle(Contract::Serialize, "sent")
}

#[must_use]
pub fn accepted() -> Schema {
    bundle(Contract::Deserialize, "accepted")
}

fn bundle(contract: Contract, direction: &str) -> Schema {
    let mut settings = SchemaSettings::draft2020_12();
    settings.contract = contract;
    let mut generator = settings.into_generator();
    for root in ROOTS {
        root(&mut generator);
    }
    let definitions = generator.take_definitions(true);
    json_schema!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://github.com/philbert440/rivethub-runtime/contract/{VERSION}/{direction}.schema.json"),
        "title": format!("RivetHub contract ({direction} by the runtime)"),
        "version": VERSION,
        "$defs": definitions,
    })
}
